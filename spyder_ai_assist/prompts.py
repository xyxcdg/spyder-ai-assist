"""提示词构造：与 VS Code 版 dsh-window 完全一致的四个模板。

- build_prompt：整篇讲解（四段，正文 ≤400 字）
- build_coach_prompt：边写边讲 / 我卡住了（三段，≤300/260 字）
- build_ask_prompt：面板内提问（结论先行，≤400 字，可带当前文件上下文）
"""

CODE_CLIP = 12000
ASK_CODE_CLIP = 6000


def _clip(code, limit, tail_note):
    if len(code) > limit:
        return code[:limit] + "\n...（已截断，只讲前面部分）"
    return code


def build_prompt(code, lang, file_name, label):
    clipped = _clip(code, CODE_CLIP, True)
    return "\n".join([
        "你是编程入门老师，讲给刚学编程的新手。用中文 Markdown，固定四段：",
        "",
        "## 这段在做什么",
        "一到两句，说清目的。",
        "",
        "## 关键几行",
        "列表 3~5 条，每条一句：这行在干什么、为什么必须这么写、写错会怎样。",
        "",
        "## 你必须懂的概念",
        "2~4 条，用大白话解释涉及的变量/循环/类型等，不要假设我懂。",
        "",
        "## 下一步你写这个",
        "给一段 5~12 行、可以直接粘贴运行的代码（和上面知识点相关、稍难一点），再用一句话说明为什么练它、写完应该看到什么结果。",
        "",
        "硬要求：正文总共 400 字以内（代码块不计）；不寒暄、不总结段、不重复贴代码全文。",
        "",
        "语言：" + lang + "，文件名：" + file_name + "（" + label + "）",
        "```" + (lang or "text"),
        clipped,
        "```",
    ])


def build_coach_prompt(code, lang, file_name, label, mode, cursor_line):
    clipped = _clip(code, CODE_CLIP, True)
    where = ("我光标停在第 %d 行附近" % cursor_line) if cursor_line > 0 else "我刚写到这里"
    if mode == "stuck":
        head = [
            "你是编程入门老师，讲给刚学编程的新手。我现在卡住了：可能写错了，也可能不知道该往下写什么。用中文 Markdown，固定三段：",
            "",
            "## 你现在写到哪",
            "一句话说清我这段代码走到哪一步了。",
            "",
            "## 有没有问题",
            "如果我写错了，直接指出第几行、错在哪、怎么改（给正确写法）；如果没错就写「没问题」。",
            "",
            "## 下一步你写这个",
            "给一段 5~12 行、能直接粘贴运行的代码，再用一句话说明为什么写它、写完应该看到什么结果。",
            "",
            "硬要求：正文总共 300 字以内（代码不计）；不寒暄、不总结、不重复贴我的代码全文。",
        ]
    else:
        head = [
            "你是编程入门老师，讲给刚学编程的新手。我正在边写边学。用中文 Markdown，固定三段：",
            "",
            "## 你现在写到哪",
            "一句话说清我这段代码在干什么。",
            "",
            "## 有没有问题",
            "只指出明显写错的行（第几行、错在哪、怎么改）；没问题就写「没问题」，不要吹毛求疵。",
            "",
            "## 下一步你写这个",
            "给一段 5~12 行、能直接粘贴运行的代码，再用一句话说明为什么练它、写完应该看到什么结果。",
            "",
            "硬要求：正文总共 260 字以内（代码不计）；不寒暄、不总结、不重复贴我的代码全文。",
        ]
    return "\n".join(head + [
        "",
        "语言：" + lang + "，文件名：" + file_name + "，" + where + "。",
        "```" + (lang or "text"),
        clipped,
        "```",
    ])


def build_ask_prompt(question, ctx=""):
    extra = ""
    if ctx:
        extra = "\n\n（参考：我当前打开的文件是 %s，语言：%s）\n```%s\n%s\n```" % (
            ctx["file_name"], ctx["lang"], (ctx["lang"] or "text"), ctx["code"])
    return "\n".join([
        "你是耐心的编程入门老师，正在给一个刚学编程的新手答疑。用中文 Markdown，直接回答：不寒暄、不客套、不复述我的问题。",
        "回答结构：先一句话给结论；再分点讲清「为什么这么写」；能给例子就给一个最小、可直接运行的例子（代码用代码块）；涉及概念用大白话解释，不要假设我懂。正文 400 字以内（代码不计）。",
        "",
        "我的问题：" + question + extra,
    ])
